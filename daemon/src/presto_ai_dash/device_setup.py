"""The one-time Presto setup handoff: an encrypted, authenticated download.

The admin page offers **Set up a Presto** to a user running the daemon from
PyPI, pipx or Docker, who has no checkout of this repository. It hands them
two files for the exact build that is running:

* ``presto_setup.py`` - a standalone installer carrying the public Presto app
  files and their hashes, generated from the same bundle the daemon ships.
* ``presto_setup.enc`` - this module's output: a versioned envelope holding
  the daemon address, the persistent shared device token and the expected app
  revision, sealed with authenticated encryption.

The unlock code is never part of either file. It is generated fresh for each
handoff from 160 random bits and displayed once in the authenticated admin
page, so the person who downloads the files must also read the page. The code
is key material: HKDF-SHA256 expands it with a fresh salt into an AES-256-GCM
key, and the nonce is fresh too. Tampering, a wrong code and a malformed or
oversized envelope all fail closed with a fixed message that never repeats
input.

What this does not do: it does not expire or revoke the shared device token,
and it does not encrypt the credential the device stores. It protects the
download while the code is kept separately. A lost code or a deleted file is
recovered by generating another handoff; an exposed token is rotated only by
changing ``daemon.shared_token`` and updating every device that uses it.

Nothing here reads a credential from a URL, a log line, a command-line
argument or a temporary file. The token lives in the daemon's memory and in
the encrypted bytes the admin page serves.
"""

import base64
import binascii
import json
import re
import secrets
import socket
import threading
from datetime import datetime, timedelta, timezone
from importlib import resources

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

ENVELOPE_VERSION = 1
KDF_NAME = "HKDF-SHA256"
CIPHER_NAME = "AES-256-GCM"
# Binds the ciphertext to this protocol, so a v1 envelope cannot be replayed
# as a different kind of artifact.
AAD = b"presto-ai-dash:presto-setup:v1"
KDF_INFO = b"presto-ai-dash:presto-setup:v1"

# Refused before a single byte is decrypted.
MAX_ENVELOPE_BYTES = 8192
MAX_PAYLOAD_BYTES = 4096
SALT_BYTES = 16
NONCE_BYTES = 12
KEY_BYTES = 32
# 20 random bytes are exactly 32 base32 characters: 160 bits of key material.
CODE_BYTES = 20
CODE_CHARS = 32
GROUP_CHARS = 4
CODE_ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567"

HANDOFF_NAME = "presto_setup.enc"
SCRIPT_NAME = "presto_setup.py"
REVISION_CHARS = 12
# The shortest shared device token a handoff will carry to a device.
MIN_TOKEN_CHARS = 16
TEMPLATE_FOLDER = "setup"
TEMPLATE_NAME = "presto_setup_template.py"
TEMPLATE_BEGIN = ("# ==== BEGIN embedded bundle (generated by "
                  "presto_ai_dash.device_setup; do not edit) ====")
TEMPLATE_END = "# ==== END embedded bundle ===="

# How many prepared handoffs one daemon keeps, and for how long. A handoff is
# only useful while the person is at the computer with the USB cable; keeping
# it longer would keep a copy of the device token in memory for no reason.
MAX_HANDOFFS = 8
HANDOFF_TTL_SECONDS = 1800
MAX_SCRIPT_CACHE = 2

# The device's own settings the handoff may carry, with the range each must be
# in. They are defaults for a new device, never a way to weaken a bound.
SETTING_LIMITS = {
    "poll_interval": (5, 3600),
    "retry_interval": (5, 3600),
    "http_timeout": (2, 60),
    "wifi_timeout": (2, 120),
    "offline_after_s": (10, 3600),
}

_HOSTNAME = re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9.-]{0,251}[A-Za-z0-9])?$")
_REVISION = re.compile(r"^[0-9a-f]{64}$")
_OTA_HOSTNAME = re.compile(r"^[a-z0-9](?:[a-z0-9.-]{0,251}[a-z0-9])?$")
_RELEASE = re.compile(r"^[0-9A-Za-z][0-9A-Za-z._+-]{0,63}$")
_DEVICE_NAME = re.compile(r"^[ -~]{1,32}$")
_LOOPBACK = frozenset(("127.0.0.1", "localhost", "::1", "0.0.0.0", "::"))


class SetupError(Exception):
    """A setup request that cannot be served, with a fixed, safe message."""


class SetupUnavailable(SetupError):
    """This build cannot prepare a download at all (no app files or no token)."""


# -- the unlock code -------------------------------------------------------

def new_unlock_code():
    """A fresh code: 160 random bits, written as eight groups of four.

    ``secrets`` is the OS's cryptographic random source. The code is
    independent for every handoff, so two downloads never share a key.
    """
    text = base64.b32encode(secrets.token_bytes(CODE_BYTES)).decode("ascii")
    text = text.rstrip("=")
    if len(text) != CODE_CHARS:  # pragma: no cover - a property of the sizes above
        raise SetupError("the setup unlock code could not be generated")
    return "-".join(text[index:index + GROUP_CHARS]
                    for index in range(0, len(text), GROUP_CHARS))


def code_bytes(code):
    """The key material of a typed code, or ``SetupError``.

    Dashes, spaces and lower case are accepted because people retype the code
    from a screen by hand. The result is exactly 20 bytes, never a truncated
    or padded guess.
    """
    if not isinstance(code, str):
        raise SetupError("Enter the setup unlock code shown in the admin page.")
    text = "".join(code.split()).replace("-", "").upper()
    if len(text) != CODE_CHARS or any(char not in CODE_ALPHABET for char in text):
        raise SetupError("That is not a setup unlock code. Copy all 32 letters and digits.")
    padding = "=" * ((8 - len(text) % 8) % 8)
    try:
        return base64.b32decode(text + padding)
    except (binascii.Error, ValueError):
        raise SetupError("That is not a setup unlock code. "
                         "Copy all 32 letters and digits.") from None


def _key(raw_code, salt):
    return HKDF(algorithm=hashes.SHA256(), length=KEY_BYTES, salt=salt,
                info=KDF_INFO).derive(raw_code)


def _canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8")


# -- the encrypted envelope ------------------------------------------------

def build_handoff(payload, code):
    """The sealed bytes of one handoff. The payload is validated first."""
    validate_payload(payload)
    plain = _canonical(payload)
    if len(plain) > MAX_PAYLOAD_BYTES:
        raise SetupError("the setup configuration is too large")
    raw_code = code_bytes(code)
    salt = secrets.token_bytes(SALT_BYTES)
    nonce = secrets.token_bytes(NONCE_BYTES)
    sealed = AESGCM(_key(raw_code, salt)).encrypt(nonce, plain, AAD)
    envelope = {"v": ENVELOPE_VERSION,
                "kdf": KDF_NAME,
                "cipher": CIPHER_NAME,
                "salt": base64.b64encode(salt).decode("ascii"),
                "nonce": base64.b64encode(nonce).decode("ascii"),
                "ct": base64.b64encode(sealed).decode("ascii")}
    return _canonical(envelope)


def open_handoff(data, code):
    """The payload of one handoff, or ``SetupError``.

    Every check happens before decryption where it can: the size, the
    envelope's exact shape, the field lengths. A wrong code and a tampered
    ciphertext are reported as the same failure, because telling them apart
    would confirm a guessed code.
    """
    if not isinstance(data, (bytes, bytearray)):
        raise SetupError("The setup file could not be read.")
    if len(data) > MAX_ENVELOPE_BYTES:
        raise SetupError("The setup file is larger than a setup handoff can be.")
    try:
        envelope = json.loads(bytes(data).decode("utf-8"))
    except (ValueError, UnicodeError, RecursionError):
        raise SetupError("The setup file is not a setup handoff.") from None
    if not isinstance(envelope, dict) or set(envelope) != {
            "v", "kdf", "cipher", "salt", "nonce", "ct"}:
        raise SetupError("The setup file is not a setup handoff of a supported version.")
    if (envelope["v"] != ENVELOPE_VERSION or envelope["kdf"] != KDF_NAME or
            envelope["cipher"] != CIPHER_NAME):
        raise SetupError("The setup file is not a setup handoff of a supported version.")
    salt = _decode(envelope["salt"], SALT_BYTES)
    nonce = _decode(envelope["nonce"], NONCE_BYTES)
    sealed = _decode(envelope["ct"], None)
    if len(sealed) > MAX_PAYLOAD_BYTES + 16:
        raise SetupError("The setup file is larger than a setup handoff can be.")
    raw_code = code_bytes(code)
    try:
        plain = AESGCM(_key(raw_code, salt)).decrypt(nonce, sealed, AAD)
    except (InvalidTag, ValueError):
        raise SetupError("The unlock code did not open the setup file. Check the code "
                         "in the admin page and try again.") from None
    if len(plain) > MAX_PAYLOAD_BYTES:
        raise SetupError("The setup file's contents are too large.")
    try:
        payload = json.loads(plain.decode("utf-8"))
    except (ValueError, UnicodeError, RecursionError):
        raise SetupError("The setup file's contents are not a setup configuration.") from None
    validate_payload(payload)
    return payload


def _decode(value, length):
    if not isinstance(value, str):
        raise SetupError("The setup file is not a setup handoff.")
    try:
        raw = base64.b64decode(value.encode("ascii"), validate=True)
    except (binascii.Error, UnicodeError):
        raise SetupError("The setup file is not a setup handoff.") from None
    if length is not None and len(raw) != length:
        raise SetupError("The setup file is not a setup handoff.")
    return raw


# -- the payload -----------------------------------------------------------

def bare_host(host):
    """A single-label name the Presto cannot resolve: no dot, and not IPv6."""
    host = str(host or "")
    return bool(host) and "." not in host and ":" not in host


def valid_host(value):
    """Whether a value can be the daemon's host as the device reaches it.

    An LAN IPv4 literal is what the device documentation recommends. A plain
    hostname is accepted because a private DNS name is a legitimate choice;
    a scheme, a path, a port or whitespace is not, because the device builds
    ``http://<host>:<port>/`` from it.
    """
    if not isinstance(value, str) or not value or len(value) > 253:
        return False
    if value != value.strip() or any(char.isspace() for char in value):
        return False
    if "://" in value or "/" in value or ":" in value or "?" in value or "#" in value:
        return False
    if value.startswith(".") or value.endswith(".") or ".." in value:
        return False
    if value.lower() in _LOOPBACK or value.lower().endswith(".localhost"):
        # A device on another machine cannot reach this computer's loopback.
        return False
    if all(char.isdigit() or char == "." for char in value):
        parts = value.split(".")
        return (len(parts) == 4 and
                all(part.isdigit() and str(int(part)) == part and 0 <= int(part) <= 255
                    for part in parts))
    return bool(_HOSTNAME.match(value))


def probe_address(host, port, timeout=4):
    """Whether a daemon answers at host:port, seen from this computer.

    It asks only ``/healthz``, which needs no token and says nothing but that a
    daemon is alive. The result is "ok", "dns", "refused", "timeout", "error" or
    ``http_<status>``. This is the daemon's view, not the Presto's: it can only
    warn, and the setup script and the Presto check from where they are.
    """
    try:
        address = socket.getaddrinfo(host, port, socket.AF_INET, socket.SOCK_STREAM)[0][-1]
    except (OSError, IndexError):
        return "dns"
    reply = b""
    try:
        with socket.create_connection(address, timeout=timeout) as link:
            link.sendall(b"GET /healthz HTTP/1.0\r\nHost: presto\r\n\r\n")
            while len(reply) < 384:
                chunk = link.recv(128)
                if not chunk:
                    break
                reply += chunk
    except socket.timeout:
        return "timeout"
    except ConnectionRefusedError:
        return "refused"
    except OSError:
        return "error"
    words = reply.split(b"\r\n", 1)[0].split(b" ")
    code = int(words[1]) if len(words) > 1 and words[1].isdigit() else 0
    if code == 200 and b'"ok": true' in reply:
        return "ok"
    return "http_%d" % code if code else "error"


def address_warning(result, host, port):
    """The fixed warning for a probe result that is not "ok"."""
    where = "%s:%d" % (host, port)
    if result == "dns":
        what = "This computer could not look up %s." % host
    elif result == "refused":
        what = "Nothing is listening at %s." % where
    elif result == "timeout":
        what = "%s did not answer in time." % where
    else:
        what = "Something answered at %s, but it did not answer as the daemon." % where
    return (what + " Check the address and port for a typo. If the daemon is in a container "
            "or behind another address this computer cannot use, this can be a false alarm: "
            "the setup script checks again from the computer the Presto is plugged into, "
            "and the Presto checks before anything is changed.")


def validate_payload(payload):
    """Refuse anything that is not exactly the documented v1 shape."""
    base = {"v", "daemon", "device", "app", "release", "created_at"}
    if not isinstance(payload, dict) or set(payload) not in (base, base | {"ota"}):
        raise SetupError("The setup configuration does not have the expected shape.")
    if "ota" in payload:
        ota = payload["ota"]
        if (not isinstance(ota, dict) or set(ota) != {"hostname", "ca"} or
                not isinstance(ota["hostname"], str) or not _OTA_HOSTNAME.match(ota["hostname"])):
            raise SetupError("The setup configuration's update settings are not usable.")
        try:
            ca = base64.b64decode(ota["ca"].encode("ascii"), validate=True)
        except (AttributeError, binascii.Error, UnicodeError, ValueError):
            raise SetupError("The setup configuration's update settings are not usable.") from None
        if not 64 <= len(ca) <= 4096:
            raise SetupError("The setup configuration's update settings are not usable.")
    if payload["v"] != 1:
        raise SetupError("The setup configuration is not a supported version.")
    daemon = payload["daemon"]
    if not isinstance(daemon, dict) or set(daemon) != {"host", "port", "token"}:
        raise SetupError("The setup configuration does not have the expected shape.")
    if not valid_host(daemon["host"]):
        raise SetupError("The setup configuration's daemon address is not usable.")
    port = daemon["port"]
    if type(port) is not int or not 1 <= port <= 65535:
        raise SetupError("The setup configuration's daemon port is not usable.")
    token = daemon["token"]
    if (not isinstance(token, str) or not MIN_TOKEN_CHARS <= len(token) <= 512 or
            not token.isascii() or any(char.isspace() for char in token)):
        raise SetupError("The setup configuration's device token is not usable.")
    device = payload["device"]
    if not isinstance(device, dict) or set(device) != {"name", "settings", "wifi"}:
        raise SetupError("The setup configuration does not have the expected shape.")
    if device["wifi"] not in ("set", "keep"):
        raise SetupError("The setup configuration's Wi-Fi choice is not usable.")
    if not isinstance(device["name"], str) or not _DEVICE_NAME.match(device["name"]):
        raise SetupError("The setup configuration's device name is not usable.")
    settings = device["settings"]
    if not isinstance(settings, dict) or set(settings) != set(SETTING_LIMITS):
        raise SetupError("The setup configuration's defaults are not usable.")
    for key, (low, high) in SETTING_LIMITS.items():
        value = settings[key]
        if type(value) is not int or not low <= value <= high:
            raise SetupError("The setup configuration's defaults are not usable.")
    app = payload["app"]
    if not isinstance(app, dict) or set(app) != {"revision", "label"}:
        raise SetupError("The setup configuration does not have the expected shape.")
    if not isinstance(app["revision"], str) or not _REVISION.match(app["revision"]):
        raise SetupError("The setup configuration's app revision is not usable.")
    if app["label"] != app["revision"][:REVISION_CHARS]:
        raise SetupError("The setup configuration's app revision is not consistent.")
    release = payload["release"]
    if not isinstance(release, dict) or set(release) != {"version"}:
        raise SetupError("The setup configuration does not have the expected shape.")
    if not isinstance(release["version"], str) or not _RELEASE.match(release["version"]):
        raise SetupError("The setup configuration's release version is not usable.")
    created = payload["created_at"]
    if not isinstance(created, str) or len(created) > 40:
        raise SetupError("The setup configuration's timestamp is not usable.")
    return payload


def build_payload(snapshot, host, port, token, device_name, release, settings=None,
                  now=None, wifi="set", ota=None):
    """The configuration one handoff carries for one running daemon build.

    ``snapshot`` is the daemon's verified public app bundle. The shared device
    token is included; the admin token never is, and there is no parameter for
    one here on purpose. ``wifi`` is ``"set"`` when the setup script should collect the
    Wi-Fi network and ``"keep"`` when the Presto must keep the one it already has.
    ``ota`` is the daemon's update identity (its ``hostname`` and public
    ``ca_der``); the device is told to trust it for app downloads.
    """
    values = dict(DEFAULT_SETTINGS)
    values.update(settings or {})
    moment = now or datetime.now(timezone.utc)
    payload = {
        "v": 1,
        "daemon": {"host": host, "port": port, "token": token},
        "device": {"name": device_name, "settings": values, "wifi": wifi},
        "app": {"revision": snapshot["revision"],
                "label": snapshot["revision"][:REVISION_CHARS]},
        "release": {"version": release},
        "created_at": moment.replace(microsecond=0).isoformat().replace("+00:00", "Z"),
    }
    if ota is not None:
        payload["ota"] = {"hostname": ota.hostname,
                          "ca": base64.b64encode(ota.ca_der).decode("ascii")}
    return validate_payload(payload)


# The defaults a new device gets unless the admin chooses otherwise. They match
# ``presto/config.example.py`` so a generated config and a hand-written one
# behave the same.
DEFAULT_SETTINGS = {
    "poll_interval": 15,
    "retry_interval": 12,
    "http_timeout": 8,
    "wifi_timeout": 10,
    "offline_after_s": 30,
}


# -- the standalone installer ---------------------------------------------

def template_text():
    """The standalone installer's source, as shipped in this package."""
    return resources.files("presto_ai_dash").joinpath(
        TEMPLATE_FOLDER, TEMPLATE_NAME).read_text(encoding="utf-8")


def render_setup_script(snapshot, release, template=None):
    """``presto_setup.py`` carrying exactly this bundle, as bytes.

    The output is deterministic for a bundle and a release, so a wheel and a
    container image built from one commit serve byte-identical bytes. The
    rendered file imports nothing from this package: it must run on a computer
    that has neither the daemon nor this repository.
    """
    text = (template_text() if template is None else template).replace("\r\n", "\n")
    start = text.find(TEMPLATE_BEGIN)
    end = text.find(TEMPLATE_END)
    if start < 0 or end < start:
        raise SetupError("the setup installer template is incomplete")
    slot, boot = snapshot.get("slot"), snapshot.get("bootstrap")
    if not slot or not boot:
        raise SetupError("This build has no Presto bootstrap or slot bundle to install.")
    block = "".join([TEMPLATE_BEGIN, "\n",
                     "BUNDLE = ", repr({"revision": snapshot["revision"],
                                        "slot": {"revision": slot["revision"],
                                                 "files": dict(sorted(slot["files"].items()))},
                                        "boot": {"files": dict(sorted(boot["files"].items()))},
                                        "bootstrap": int(boot["version"])}), "\n",
                     "RELEASE = ", repr(release), "\n",
                     TEMPLATE_END, "\n"])
    rendered = text[:start] + block + text[end + len(TEMPLATE_END) + 1:]
    compile(rendered, SCRIPT_NAME, "exec")
    return rendered.encode("utf-8")


# -- the admin page's setup service ---------------------------------------

class SetupService:
    """Prepare setup downloads for the running daemon build.

    Handoffs live in memory only, are capped in number and in age, and are
    dropped when the admin page discards them. Losing one - a restart, a lost
    code - costs a new handoff, never the device token.
    """

    def __init__(self, bundle_provider, shared_token, host, port, release,
                 clock=None, token_temporary=False, template=None,
                 container=False, ota=None, address_probe=None):
        self._bundle_provider = bundle_provider
        # Looks for the daemon at the address being prepared, so a typo is
        # flagged at once. None (the default) looks nowhere.
        self._address_probe = address_probe
        # The daemon's update identity, given to every device it sets up.
        self._ota = ota
        self._token = shared_token or ""
        self._host = host or ""
        self._port = int(port)
        self.release = release
        self._clock = clock or (lambda: datetime.now(timezone.utc))
        self.token_temporary = bool(token_temporary)
        self._template = template
        # A container's own address is not one the Presto can reach, so it is
        # only discovered and suggested when this process is on the bare host.
        self._container = bool(container)
        self._lock = threading.Lock()
        self._handoffs = {}
        self._scripts = {}

    # -- what the page reads before asking for anything -------------------

    def bundle(self):
        """The verified public app bundle, or None when this build has none."""
        try:
            return self._bundle_provider()
        except Exception:
            return None

    def state(self, host_header=None):
        snapshot = self.bundle()
        suggested = self.suggested_hosts(host_header)
        if snapshot is None:
            return {"v": 1, "available": False, "reason": "bundle_unavailable",
                    "release": self.release}
        with self._lock:
            count = len(self._handoffs)
        return {"v": 1, "available": True,
                "release": self.release,
                "revision": snapshot["revision"],
                "label": snapshot["revision"][:REVISION_CHARS],
                "daemon": {"host": suggested[0] if suggested else "",
                           "port": self._port,
                           "suggested": suggested},
                "token_temporary": self.token_temporary,
                "downloads": {"script": SCRIPT_NAME, "handoff": HANDOFF_NAME},
                "handoffs": count}

    def suggested_hosts(self, host_header=None):
        """Addresses the device could plausibly reach, best first.

        The browser's own Host header is the best hint that the daemon answers
        on a name the user already uses. A container's bind address (0.0.0.0)
        is useless to a device, so it is never suggested, and a container's own
        address is not discovered at all: in Docker that is the container's
        bridge address, while the device reaches the published host address.
        """
        candidates = []
        browser = _host_only(host_header)
        if browser and browser.lower() not in _LOOPBACK:
            candidates.append(browser)
        configured = (self._host or "").strip()
        if configured and configured.lower() not in _LOOPBACK:
            candidates.append(configured)
        if not self._container:
            discovered = _lan_address()
            if discovered:
                candidates.append(discovered)
        unique = []
        for name in candidates:
            if valid_host(name) and name not in unique:
                unique.append(name)
        # A bare name ("server", no dot) works on a computer that adds its network's
        # DNS domain, but the Presto adds none and cannot look it up (measured), so a
        # full name or an address comes first. The order is otherwise kept.
        unique.sort(key=bare_host)
        return unique[:5]

    # -- preparing a handoff ----------------------------------------------

    def create(self, host, port, device_name="presto", settings=None, wifi=True):
        """A new handoff and its one-time unlock code.

        The code is returned once, for display in the authenticated page. It
        is stored only so the page can discard the handoff; it is never served
        by a download route and never written anywhere.
        """
        snapshot = self.bundle()
        if snapshot is None:
            raise SetupUnavailable("This build has no Presto app files to install. "
                                   "Use a release wheel or the container image.")
        if not self._token:
            raise SetupUnavailable("This daemon has no shared device token to give the device.")
        if len(self._token) < MIN_TOKEN_CHARS:
            # A configuration problem, not a bad request: say what to change.
            raise SetupUnavailable(
                "The daemon's shared device token is shorter than %d characters, too "
                "short to give a device. Set a longer daemon.shared_token (or "
                "DASH_SHARED_TOKEN), restart the daemon, then prepare the download "
                "again." % MIN_TOKEN_CHARS)
        if not valid_host(host):
            raise SetupError("Enter the IPv4 address or name the Presto can reach, "
                             "without http://, a path or a port.")
        if type(port) is not int or not 1 <= port <= 65535:
            raise SetupError("Enter the daemon's port as a number from 1 to 65535.")
        if not isinstance(device_name, str) or not _DEVICE_NAME.match(device_name):
            raise SetupError("The device name must be printable ASCII of at most 32 characters.")
        if type(wifi) is not bool:
            raise SetupError("Say whether the Presto's Wi-Fi should be set: true or false.")
        warnings = []
        if self._address_probe is not None:
            try:
                seen = self._address_probe(host, port)
            except Exception:
                seen = "ok"  # a probe that fails is no reason to doubt the address
            if seen != "ok":
                warnings.append(address_warning(seen, host, port))
        payload = build_payload(snapshot, host, port, self._token, device_name,
                                self.release, settings=settings, now=self._clock(),
                                wifi="set" if wifi else "keep", ota=self._ota)
        code = new_unlock_code()
        envelope = build_handoff(payload, code)
        handoff_id = secrets.token_hex(16)
        expires = self._clock() + timedelta(seconds=HANDOFF_TTL_SECONDS)
        with self._lock:
            self._prune_locked()
            if len(self._handoffs) >= MAX_HANDOFFS:
                oldest = min(self._handoffs, key=lambda key: self._handoffs[key]["created"])
                del self._handoffs[oldest]
            self._handoffs[handoff_id] = {"envelope": envelope, "code": code,
                                          "created": self._clock(), "expires": expires,
                                          "revision": snapshot["revision"],
                                          "host": host, "port": port}
        return {"v": 1, "handoff_id": handoff_id, "unlock_code": code,
                "release": self.release,
                "revision": snapshot["revision"],
                "label": snapshot["revision"][:REVISION_CHARS],
                "daemon": {"host": host, "port": port},
                "device_name": device_name,
                "wifi": wifi,
                "warnings": warnings,
                "downloads": {
                    "script": "/api/admin/presto-setup/%s/script" % handoff_id,
                    "handoff": "/api/admin/presto-setup/%s/handoff" % handoff_id},
                "expires_at": expires.replace(microsecond=0).isoformat().replace("+00:00", "Z")}

    def handoff(self, handoff_id):
        """The encrypted bytes of one prepared handoff."""
        entry = self._entry(handoff_id)
        return entry["envelope"]

    def script(self, handoff_id):
        """The standalone installer that matches this handoff's bundle."""
        entry = self._entry(handoff_id)
        snapshot = self.bundle()
        if snapshot is None:
            raise SetupError("This build has no Presto app files to install.")
        if snapshot["revision"] != entry["revision"]:
            raise SetupError("The Presto app changed since this handoff was prepared. "
                             "Prepare the download again.")
        key = (snapshot["revision"], self.release)
        with self._lock:
            cached = self._scripts.get(key)
        if cached is None:
            cached = render_setup_script(snapshot, self.release, self._template)
            with self._lock:
                self._scripts[key] = cached
                while len(self._scripts) > MAX_SCRIPT_CACHE:
                    self._scripts.pop(next(iter(self._scripts)))
        return cached

    def discard(self, handoff_id):
        """Forget one handoff; its files stay valid until they are used."""
        with self._lock:
            return self._handoffs.pop(handoff_id, None) is not None

    def _entry(self, handoff_id):
        if not isinstance(handoff_id, str) or not re.fullmatch(r"[0-9a-f]{32}", handoff_id):
            raise KeyError(handoff_id)
        with self._lock:
            self._prune_locked()
            entry = self._handoffs.get(handoff_id)
        if entry is None:
            raise KeyError(handoff_id)
        return entry

    def _prune_locked(self):
        now = self._clock()
        expired = [key for key, entry in self._handoffs.items()
                   if entry["expires"] <= now]
        for key in expired:
            del self._handoffs[key]


def _host_only(value):
    """The hostname of a Host header, without brackets or a port."""
    text = (value or "").strip().lower()
    if not text:
        return ""
    if text.startswith("["):
        end = text.find("]")
        return text[1:end] if end > 0 else ""
    if text.count(":") == 1:
        name, _, port = text.partition(":")
        if port.isdigit():
            return name
    return text


def _lan_address():
    """This machine's outbound IPv4 address, when the OS can say.

    No packet is sent: connecting a UDP socket only asks the routing table
    which local address would be used. An offline machine simply has none.
    """
    probe = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        probe.settimeout(0.2)
        probe.connect(("192.0.2.1", 9))  # TEST-NET-1, never routed
        address = probe.getsockname()[0]
    except OSError:
        return None
    finally:
        probe.close()
    if not address or address.startswith("127."):
        return None
    return address
