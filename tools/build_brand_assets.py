"""Copy approved web artwork and derive compact device sprites (stdlib only).

Run after updating assets/brand/. --check detects stale derived files without
writing. The Presto needs no image decoder, filesystem reads or extra library:
its generated brand.py joins the existing shared Python app inventory.
"""

import argparse
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
COLOURS = ((255, 139, 62), (49, 212, 232), (23, 40, 63), (48, 66, 93))


def rgba_png(path):
    """Read the bundle's non-interlaced 8-bit RGBA exports, including filters."""
    data = path.read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("not a PNG: " + str(path))
    compressed = bytearray()
    position = 8
    while position < len(data):
        length, kind = struct.unpack_from(">I4s", data, position)
        chunk = data[position + 8:position + 8 + length]
        if kind == b"IHDR":
            width, height, depth, colour, compression, filtering, interlace = struct.unpack(">IIBBBBB", chunk)
            if (depth, colour, compression, filtering, interlace) != (8, 6, 0, 0, 0):
                raise ValueError("expected non-interlaced 8-bit RGBA: " + str(path))
        elif kind == b"IDAT":
            compressed.extend(chunk)
        position += length + 12
    raw = zlib.decompress(compressed)
    stride = width * 4
    if len(raw) != (stride + 1) * height:
        raise ValueError("wrong PNG data length")
    pixels = bytearray()
    previous = bytearray(stride)
    for y in range(height):
        offset = y * (stride + 1)
        mode = raw[offset]
        row = bytearray(raw[offset + 1:offset + 1 + stride])
        for x in range(stride):
            left = row[x - 4] if x >= 4 else 0
            up = previous[x]
            corner = previous[x - 4] if x >= 4 else 0
            if mode == 0:
                prediction = 0
            elif mode == 1:
                prediction = left
            elif mode == 2:
                prediction = up
            elif mode == 3:
                prediction = (left + up) // 2
            elif mode == 4:
                p = left + up - corner
                distances = (abs(p - left), abs(p - up), abs(p - corner))
                prediction = (left, up, corner)[distances.index(min(distances))]
            else:
                raise ValueError("unknown PNG filter")
            row[x] = (row[x] + prediction) & 255
        pixels.extend(row)
        previous = row
    return width, height, pixels


def sprite(path, size):
    width, height, pixels = rgba_png(path)
    if (width, height) != (size, size):
        raise ValueError("wrong icon dimensions")
    # Four brand colours, transparent outside. Quantise antialiasing instead
    # of baking a background into the icon; it works on every app screen.
    rows = []
    for y in range(size):
        row = []
        for x in range(size):
            offset = (y * size + x) * 4
            rgb = pixels[offset:offset + 3]
            colour = min(range(len(COLOURS)), key=lambda i: sum(
                (rgb[c] - COLOURS[i][c]) ** 2 for c in range(3)))
            row.append(colour if pixels[offset + 3] >= 128 else None)
        rows.append(row)
    runs = [bytearray() for _ in COLOURS]
    for y, row in enumerate(rows):
        x = 0
        while x < size:
            colour = row[x]
            end = x + 1
            while end < size and row[end] == colour:
                end += 1
            if colour is not None:
                runs[colour].extend((x, y, end - x))
            x = end
    return tuple(bytes(run) for run in runs)


def outputs(root=ROOT):
    source = root / "assets/brand"
    result = {}
    # Browser chrome fixes the favicon size. Remove only the outer canvas
    # padding so the approved artwork fills more of that tiny slot.
    favicon = (source / "presto-ai-dash-icon.svg").read_text(encoding="utf-8").replace(
        'viewBox="0 0 512 512"', 'viewBox="50 50 412 412"', 1).encode("utf-8")
    for folder in ("daemon/src/presto_ai_dash/web", "docs/user/images/brand", "website/assets/brand"):
        for name in ("presto-ai-dash-icon.svg", "presto-ai-dash-favicon.ico"):
            result[root / folder / name] = (source / name).read_bytes()
        result[root / folder / "presto-ai-dash-favicon.svg"] = favicon
    result[root / "tools/presto_preview/favicon.svg"] = favicon
    # The admin page shows this one in the browser tab while a daemon update is
    # available: the favicon with an amber badge, ringed in the page's dark so it
    # reads against any tab colour.
    badge = ('  <circle cx="400" cy="400" r="66" fill="#FBBF24" stroke="#0B1220" '
             'stroke-width="16"/>\n</svg>').encode("utf-8")
    result[root / "daemon/src/presto_ai_dash/web/presto-ai-dash-favicon-update.svg"] = (
        favicon.replace(b"</svg>", badge, 1))
    lines = ['"""Approved Watchful Meter sprites. Generated by tools/build_brand_assets.py."""',
             '', 'NAME = "Presto AI Dash"',
             'TAGLINE = "Always in view. Never in your way."',
             'TAGLINE_LINES = ("Always in view.", "Never in your way.")',
             'COLOURS = ' + repr(COLOURS), '',
             '# Per colour: compact (x, y, width) byte triples; each span is one pixel high.',
             'SPRITES = {']
    for size in (16, 32, 64):
        lines.append('    %d: (' % size)
        for run in sprite(source / ("png/presto-ai-dash-%d.png" % size), size):
            lines.append('        %r,' % run)
        lines.append('    ),')
    lines.extend(('}', ''))
    result[root / "presto/brand.py"] = '\n'.join(lines).encode('ascii')
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if stale:
        raise SystemExit("Run tools/build_brand_assets.py: " + ", ".join(stale))
    print("Brand assets %s." % ("verified" if args.check else "generated"))


if __name__ == "__main__":
    main()
