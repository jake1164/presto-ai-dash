"""Refresh the readers embedded in the one-file collector.

The collector is one file that people copy to other machines. Its readers (the
Claude activity reader, the Claude usage-cache reader, the Codex report rules
and the small Codex app-server client) are the daemon's own modules, so the
daemon and the collector cannot read a file two different ways. The file holds
their source, word for word, between two marker lines; this tool rewrites that
block from the modules. A test fails when the block is out of date.

    python tools/build_collector.py          rewrite the block
    python tools/build_collector.py --check  exit 1 when it is out of date
"""

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "daemon" / "src" / "presto_ai_dash"
COLLECTOR = PACKAGE / "collectors" / "presto_collector.py"

# Embedded name -> the module it is copied from. The order is the order they load.
SECTIONS = (
    ("child_env", PACKAGE / "child_env.py"),
    ("claude_activity", PACKAGE / "collectors" / "claude_activity.py"),
    ("claude_usage_cache", PACKAGE / "collectors" / "claude_usage_cache.py"),
    ("codex_report", PACKAGE / "collectors" / "codex_report.py"),
    ("codex_rpc", PACKAGE / "sources" / "_codex_rpc.py"),
)

BEGIN = "# ==== BEGIN embedded readers (generated by tools/build_collector.py; do not edit) ===="
END = "# ==== END embedded readers ===="
QUOTE = "'" * 3


def source_text(path):
    """A module's source with LF line endings, which is how the repository keeps it."""
    text = Path(path).read_bytes().decode("utf-8").replace("\r\n", "\n")
    if QUOTE in text:
        raise ValueError("%s contains three single quotes in a row, which the embedded "
                         "copy cannot hold" % path)
    if text.rstrip("\n").endswith("\\"):
        raise ValueError("%s ends with a backslash" % path)
    return text


def render_block(sections=SECTIONS):
    """The generated block, markers included, ending with a newline."""
    parts = [BEGIN + "\n_EMBEDDED = {\n"]
    for name, path in sections:
        # The module's text sits directly inside the quotes, so the string is
        # exactly the module and nothing is added or taken away.
        parts.append("    %r: r%s%s%s,\n" % (name, QUOTE, source_text(path), QUOTE))
    parts.append("}\n" + END + "\n")
    return "".join(parts)


def rebuilt(collector_text, sections=SECTIONS):
    """The collector's text with its embedded block replaced by a fresh one."""
    text = collector_text.replace("\r\n", "\n")
    start, stop = text.find(BEGIN), text.find(END)
    if start < 0 or stop < start:
        raise ValueError("the collector has no embedded-readers block")
    stop += len(END) + 1
    return text[:start] + render_block(sections) + text[stop:]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="report whether the block is current; change nothing")
    arguments = parser.parse_args(argv)
    current = COLLECTOR.read_bytes().decode("utf-8").replace("\r\n", "\n")
    fresh = rebuilt(current)
    if fresh == current:
        print("the embedded readers are current")
        return 0
    if arguments.check:
        print("the embedded readers are out of date: run tools/build_collector.py")
        return 1
    COLLECTOR.write_bytes(fresh.encode("utf-8"))
    print("rewrote the embedded readers in %s" % COLLECTOR)
    return 0


if __name__ == "__main__":
    sys.exit(main())
